    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        if (cmbCustomer.getSelectedItem() == null || cmbItem.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Choose a customer and an available bouquet.");
            return;
        }
        try {
            int quantity = Integer.parseInt(txtQuantity.getText().trim());
            if (quantity < 1 || quantity > 1000) {
                throw new IllegalArgumentException("Quantity must be between 1 and 1000.");
            }
            java.time.LocalDate pickup = java.time.LocalDate.parse(txtDate.getText().trim());
            if (pickup.isBefore(java.time.LocalDate.now())) {
                throw new IllegalArgumentException("Pickup date cannot be in the past.");
            }
            try (Connection con = DatabaseConnection.getConnection();
                 PreparedStatement priceQuery = con.prepareStatement(
                         "SELECT price FROM simple_bouquets WHERE id=? AND availability='Available'")) {
                priceQuery.setInt(1, Integer.parseInt(cmbItem.getSelectedItem().toString()));
                java.math.BigDecimal price;
                try (ResultSet rs = priceQuery.executeQuery()) {
                    if (!rs.next()) throw new IllegalArgumentException("This bouquet is unavailable.");
                    price = rs.getBigDecimal("price");
                }
                java.math.BigDecimal total = price.multiply(java.math.BigDecimal.valueOf(quantity));
                try (PreparedStatement pst = con.prepareStatement(
                        "INSERT INTO simple_orders(customer_id,item_id,quantity,unit_price,total,payment_method,pickup_date) VALUES (?,?,?,?,?,?,?)")) {
                    pst.setInt(1, Integer.parseInt(cmbCustomer.getSelectedItem().toString()));
                    pst.setInt(2, Integer.parseInt(cmbItem.getSelectedItem().toString()));
                    pst.setInt(3, quantity);
                    pst.setBigDecimal(4, price);
                    pst.setBigDecimal(5, total);
                    pst.setString(6, cmbPayment.getSelectedItem().toString());
                    pst.setDate(7, java.sql.Date.valueOf(pickup));
                    pst.executeUpdate();
                }
                loadRecords();
                JOptionPane.showMessageDialog(this, "Order saved. Total: LKR " + total.toPlainString());
                txtQuantity.setText("1");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

