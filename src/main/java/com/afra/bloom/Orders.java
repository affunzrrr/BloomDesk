    private void loadOptions() {
        try (Connection con = DatabaseConnection.getConnection();
             PreparedStatement customers = con.prepareStatement("SELECT id FROM simple_customers ORDER BY id");
             ResultSet rs = customers.executeQuery()) {
            while (rs.next()) cmbCustomer.addItem(rs.getString("id"));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
        try (Connection con = DatabaseConnection.getConnection();
             PreparedStatement items = con.prepareStatement("SELECT id FROM simple_bouquets WHERE availability='Available' ORDER BY id");
             ResultSet rs = items.executeQuery()) {
            while (rs.next()) cmbItem.addItem(rs.getString("id"));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void loadRecords() {
        DefaultTableModel model = (DefaultTableModel) tblRecords.getModel();
        model.setRowCount(0);
        try (Connection con = DatabaseConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(
                     "SELECT t.id, CONCAT(c.first_name,' ',c.last_name) AS customer, i.name, "
                     + "t.quantity,t.total,t.payment_method,t.pickup_date,t.created_at "
                     + "FROM simple_orders t JOIN simple_customers c ON c.id=t.customer_id "
                     + "JOIN simple_bouquets i ON i.id=t.item_id ORDER BY t.id DESC");
             ResultSet rs = pst.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[] {rs.getInt("id"), rs.getString("customer"), rs.getString("name"),
                        rs.getInt("quantity"), rs.getBigDecimal("total"), rs.getString("payment_method"),
                        rs.getDate("pickup_date"), rs.getTimestamp("created_at")});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

