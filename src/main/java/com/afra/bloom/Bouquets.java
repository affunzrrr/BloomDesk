    private void loadItems() {
        DefaultTableModel model = (DefaultTableModel) tblRecords.getModel();
        model.setRowCount(0);
        cmbItem.removeAllItems();
        try (Connection con = DatabaseConnection.getConnection();
             PreparedStatement pst = con.prepareStatement("SELECT * FROM simple_bouquets ORDER BY id");
             ResultSet rs = pst.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[] {rs.getInt("id"), rs.getString("name"),
                        rs.getString("type"), rs.getBigDecimal("price"), rs.getString("availability")});
                cmbItem.addItem(rs.getString("id"));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void loadDetails() {
        if (cmbItem.getSelectedItem() == null) return;
        try (Connection con = DatabaseConnection.getConnection();
             PreparedStatement pst = con.prepareStatement("SELECT * FROM simple_bouquets WHERE id=?")) {
            pst.setInt(1, Integer.parseInt(cmbItem.getSelectedItem().toString()));
            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    txtName.setText(rs.getString("name"));
                    txtType.setText(rs.getString("type"));
                    txtPrice.setText(rs.getBigDecimal("price").toPlainString());
                    txtAvailability.setText(rs.getString("availability"));
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

